data class StagedImage(val file: File, val thumb: ImageBitmap)

class CreateViewModel(private val repository: ComparisonRepository) : ViewModel() {
    var original by mutableStateOf<StagedImage?>(null)
    var generated by mutableStateOf<List<StagedImage>>(emptyList())
    var category by mutableStateOf<String?>(null)
    var saving by mutableStateOf(false)
    var busy by mutableStateOf(false)
    var error by mutableStateOf<String?>(null)
    private var committed = false

    fun setOriginal(uri: Uri) {
        viewModelScope.launch {
            busy = true
            error = null
            try {
                val staged = stage(uri)
                original?.let { repository.discardStaged(listOf(it.file)) }
                original = staged
            } catch (t: Throwable) {
                error = t.message ?: "无法读取原图"
            } finally {
                busy = false
            }
        }
    }

    fun addGenerated(uris: List<Uri>) {
        viewModelScope.launch {
            busy = true
            error = null
            try {
                val added = uris.map { stage(it) }
                generated = generated + added
            } catch (t: Throwable) {
                error = t.message ?: "无法读取生成图"
            } finally {
                busy = false
            }
        }
    }

    fun removeGenerated(file: File) {
        generated = generated.filterNot { it.file == file }
        repository.discardStaged(listOf(file))
    }

    fun save(onCreated: (Long) -> Unit) {
        val source = original ?: return
        val outputs = generated
        val chosen = category ?: return
        if (outputs.isEmpty() || saving) return
        viewModelScope.launch {
            saving = true
            error = null
            try {
                val id = repository.create(source.file, outputs.map { it.file }, chosen)
                committed = true
                original = null
                generated = emptyList()
                category = null
                committed = false
                onCreated(id)
            } catch (t: Throwable) {
                error = t.message ?: "保存失败"
            } finally {
                saving = false
            }
        }
    }

    fun discard() {
        if (!committed) {
            val files = listOfNotNull(original?.file) + generated.map { it.file }
            repository.discardStaged(files)
        }
        original = null
        generated = emptyList()
        category = null
        error = null
        committed = false
    }

    override fun onCleared() {
        discard()
    }

    private suspend fun stage(uri: Uri): StagedImage {
        val file = repository.stage(uri)
        val thumb = withContext(Dispatchers.IO) { ImageDecode.decode(file, 256) }
            ?: error("无法解码此图片")
        return StagedImage(file, thumb.asImageBitmap())
    }

    class Factory : ViewModelProvider.Factory {
        @Suppress("UNCHECKED_CAST")
        override fun <T : ViewModel> create(modelClass: Class<T>): T {
            return CreateViewModel(Graph.repository) as T
        }
    }
}

@OptIn(ExperimentalMaterial3Api::class, ExperimentalLayoutApi::class)
@Composable
fun CreateComparisonSheet(
    onDismiss: () -> Unit,
    onCreated: (Long) -> Unit,
    viewModel: CreateViewModel = viewModel(factory = CreateViewModel.Factory()),
) {
    val sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)
    val pickOriginal = rememberLauncherForActivityResult(ActivityResultContracts.PickVisualMedia()) { uri ->
        if (uri != null) viewModel.setOriginal(uri)
    }
    val pickGenerated = rememberLauncherForActivityResult(
        ActivityResultContracts.PickMultipleVisualMedia(12),
    ) { uris ->
        if (uris.isNotEmpty()) viewModel.addGenerated(uris)
    }
    val ready = viewModel.original != null && viewModel.generated.isNotEmpty() && viewModel.category != null
    ModalBottomSheet(
        onDismissRequest = {
            if (!viewModel.saving) {
                viewModel.discard()
                onDismiss()
            }
        },
        sheetState = sheetState,
        containerColor = Card,
        dragHandle = { BottomSheetDefaults.DragHandle(color = Border) },
    ) {
        Column(
            Modifier
                .fillMaxWidth()
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 16.dp)
                .padding(bottom = 28.dp),
        ) {
            Text("新建对比", color = TextPrimary, fontSize = 22.sp, fontWeight = FontWeight.Bold)
            Spacer(Modifier.height(6.dp))
            Text("先选 1 张原图，再选 1 张或多张生成图，然后选择分类。", color = TextSecondary, fontSize = 12.sp)
            Spacer(Modifier.height(16.dp))
            Text("原图", color = TextPrimary, fontSize = 14.sp, fontWeight = FontWeight.Medium)
            Spacer(Modifier.height(8.dp))
            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                val original = viewModel.original
                if (original != null) {
                    Image(
                        bitmap = original.thumb,
                        contentDescription = "原图",
                        contentScale = ContentScale.Crop,
                        modifier = Modifier.size(72.dp).clip(RoundedCornerShape(10.dp)),
                    )
                }
                SheetButton(if (original == null) "从相册选择原图" else "重新选择") {
                    pickOriginal.launch(PickVisualMediaRequest(ActivityResultContracts.PickVisualMedia.ImageOnly))
                }
            }
            Spacer(Modifier.height(16.dp))
            Text("生成图", color = TextPrimary, fontSize = 14.sp, fontWeight = FontWeight.Medium)
            Spacer(Modifier.height(8.dp))
            FlowRow(horizontalArrangement = Arrangement.spacedBy(8.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                viewModel.generated.forEach { image ->
                    BoxThumb(image.thumb) { viewModel.removeGenerated(image.file) }
                }
                SheetButton("选择一张或多张") {
                    pickGenerated.launch(PickVisualMediaRequest(ActivityResultContracts.PickVisualMedia.ImageOnly))
                }
            }
            Spacer(Modifier.height(16.dp))
            Text("分类", color = TextPrimary, fontSize = 14.sp, fontWeight = FontWeight.Medium)
            Spacer(Modifier.height(8.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Category.labels.forEach { label ->
                    val selected = viewModel.category == label
                    Text(
                        text = label,
                        color = if (selected) Color.Black else TextSecondary,
                        fontSize = 13.sp,
                        modifier = Modifier
                            .clip(CircleShape)
                            .background(if (selected) Accent else Background)
                            .border(1.dp, if (selected) Accent else Border, CircleShape)
                            .clickable { viewModel.category = label }
                            .padding(horizontal = 14.dp, vertical = 6.dp),
                    )
                }
            }
            viewModel.error?.let {
                Spacer(Modifier.height(10.dp))
                Text(it, color = Color(0xFFFF6B6B), fontSize = 12.sp)
            }
            Spacer(Modifier.height(18.dp))
            val label = when {
                viewModel.saving -> "正在处理图片…"
                viewModel.original == null -> "请先选择原图"
                viewModel.generated.isEmpty() -> "请选择生成图"
                viewModel.category == null -> "请选择分类"
                else -> "开始对比"
            }
            Row(
                Modifier
                    .fillMaxWidth()
                    .clip(CircleShape)
                    .background(if (ready && !viewModel.saving) Accent else Border)
                    .clickable(enabled = ready && !viewModel.saving && !viewModel.busy) {
                        viewModel.save(onCreated)
                    }
                    .padding(vertical = 12.dp),
                horizontalArrangement = Arrangement.Center,
                verticalAlignment = Alignment.CenterVertically,
            ) {
                if (viewModel.saving || viewModel.busy) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(16.dp).padding(end = 0.dp),
                        color = Color.Black,
                        strokeWidth = 2.dp,
                    )
                    Spacer(Modifier.size(8.dp))
                }
                Text(label, color = if (ready) Color.Black else TextSecondary, fontSize = 14.sp, fontWeight = FontWeight.Medium)
            }
        }
    }
}

@Composable
private fun SheetButton(label: String, onClick: () -> Unit) {
    Text(
        text = label,
        color = Accent,
        fontSize = 13.sp,
        modifier = Modifier
            .clip(CircleShape)
            .border(1.dp, Accent, CircleShape)
            .clickable(onClick = onClick)
            .padding(horizontal = 14.dp, vertical = 8.dp),
    )
}

@Composable
private fun BoxThumb(image: ImageBitmap, onRemove: () -> Unit) {
    Box(Modifier.size(72.dp)) {
        Image(
            bitmap = image,
            contentDescription = null,
            contentScale = ContentScale.Crop,
            modifier = Modifier.fillMaxSize().clip(RoundedCornerShape(10.dp)),
        )
        Icon(
            Icons.Filled.Close,
            contentDescription = "移除",
            tint = Color.White,
            modifier = Modifier
                .align(Alignment.TopEnd)
                .padding(4.dp)
                .size(16.dp)
                .clip(CircleShape)
                .background(Color.Black.copy(alpha = 0.6f))
                .clickable(onClick = onRemove),
        )
    }
}
